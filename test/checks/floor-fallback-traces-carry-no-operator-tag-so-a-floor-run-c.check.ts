import { test, expect } from "bun:test";
import * as mod from "../../src/index";
import type { FloorWalkContext } from "../../src/floor-walk-context";

// Define a minimal shape for trace objects to allow the test to typecheck.
interface CapturedTrace {
  id: string;
  tags?: readonly string[];
}

test("floor fallback traces must carry the dispatch operator tag", async () => {
  const capturedTraces: CapturedTrace[] = [];
  const operatorTag = "operator:ac8b0aad";

  // Construct a partial walk context to inject a trace collector and operator tag.
  // The 'persist' hook is inferred from tracing patterns elsewhere in the codebase
  // as the mechanism for observing trace side-effects. A type assertion is used
  // because the full FloorWalkContext type is not available to this test.
  const walkContext = {
    tags: [operatorTag],
    persist: (trace: CapturedTrace) => {
      capturedTraces.push(trace);
    },
  } as unknown as FloorWalkContext;

  // Execute the tool loop for a goal that has no producers, which forces a call
  // to the 'universalToolFallback' code path via runGroundedToolLoop.
  await mod.runGroundedToolLoop(
    "a goal for which no tool exists",
    ["nonexistent.shape.v1"],
    "exec_sose6wfk", // dispatchId
    walkContext,
  );

  // Find the specific trace generated by the fallback logic.
  const fallbackTrace = capturedTraces.find(t => t.id?.startsWith("universal-tool-fallback-"));
  
  expect(fallbackTrace).toBeDefined();
  // This assertion is expected to fail. The defect is that the operator tag
  // is not present on fallback traces. The test asserts the corrected behavior.
  expect(fallbackTrace?.tags).toContain(operatorTag);
});